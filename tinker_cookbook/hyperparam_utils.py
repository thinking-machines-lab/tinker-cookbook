"""
Per-model LoRA learning rates and LoRA parameter counts for Tinker base models.

Learning rates come from ``lr_multipliers.json``: a reference LR and one **LR
multiplier** per model. A model's multiplier is its optimal learning rate in a
short AdamW LoRA LR sweep on plain pretraining text, divided by the reference model's.
If ``lr_a`` is a good AdamW LoRA learning rate for model A on some task,
``lr_a * mult(B) / mult(A)`` is the corresponding learning rate for model B on
the same task (same data, batch size, number of steps, LoRA rank and optimizer).

``lr_multipliers.json`` is generated by ``python -m tinker_cookbook.lr_calibration``
from ``lr_calibration/calibration_data.json``, which records the protocol, how
the reference LR was chosen, and each model's sweep and fit.

Example::

    from tinker_cookbook import hyperparam_utils

    lr = hyperparam_utils.get_lr("Qwen/Qwen3.5-9B")
    lr_kimi = hyperparam_utils.transfer_lr(lr, "Qwen/Qwen3.5-9B", "moonshotai/Kimi-K2.6")
"""

import json
import warnings
from functools import cache
from importlib import resources
from typing import Any

from tinker_cookbook.exceptions import ConfigurationError


@cache
def _lr_table() -> dict[str, Any]:
    text = resources.files("tinker_cookbook").joinpath("lr_multipliers.json").read_text()
    return json.loads(text)


def _base_model_name(model_name: str) -> str:
    """Strip Tinker's variant suffix (e.g. ``:peft:262144``) from a model id.

    The lookup tables are keyed by the base name, but callers pass whatever
    identifier the service accepts. Some models are only served under a suffixed
    id (e.g. ``zai-org/GLM-5.3:peft:262144``), so there is no bare name to fall
    back on. Mirrors ``model_info``.
    """
    return model_name.split(":", 1)[0]


def get_lora_lr_multiplier(model_name: str) -> float:
    """Return the model's AdamW LoRA LR multiplier, relative to the reference model.

    Given two models A and B, and a learning rate LR_A that's known to be good for A,
    a good learning rate for B is
    LR_B = LR_A * get_lora_lr_multiplier(B) / get_lora_lr_multiplier(A);
    :func:`transfer_lr` computes this.

    Args:
        model_name (str): Tinker model id; ``:peft:<context>`` suffixes share the base
            model's entry.

    Returns:
        float: Multiplier; the reference model has 1.0.

    Raises:
        ConfigurationError: If the model has no calibrated LR, or is a non-LoRA variant
            (such as ``:full:...``).
    """
    _, _, variant = model_name.partition(":")
    if variant and not variant.startswith("peft"):
        raise ConfigurationError(
            f"{model_name!r}: only LoRA (':peft:...') variants are calibrated; "
            f"got variant {variant!r}"
        )
    multipliers = _lr_table()["multipliers"]
    multiplier = multipliers.get(_base_model_name(model_name))
    if multiplier is None:
        raise ConfigurationError(
            f"No calibrated learning rate for {model_name!r}. Known models: {sorted(multipliers)}. "
            "New models are added with `python -m tinker_cookbook.lr_calibration --missing`."
        )
    return float(multiplier)


def transfer_lr(lr: float, from_model: str, to_model: str) -> float:
    """Translate an AdamW LoRA learning rate tuned on one model to another model.

    The result is ``lr * mult(to_model) / mult(from_model)``. It assumes everything
    else (data, batch size, steps, LoRA rank, optimizer) stays the same. This is the
    main use of the multipliers: the learning rate you tuned carries your task's
    absolute scale, which :func:`get_lr` can only guess. These model ratios are
    calibrated for AdamW; for Dimuon, tune on the target model directly. Optimizer
    conversion is a separate estimate with its own scope in the hyperparameter guide.

    Args:
        lr (float): Learning rate known to work well for ``from_model``.
        from_model (str): Model the learning rate was tuned on.
        to_model (str): Model to translate the learning rate to.

    Returns:
        float: Learning rate for ``to_model``.
    """
    return lr * get_lora_lr_multiplier(to_model) / get_lora_lr_multiplier(from_model)


def get_lr(model_name: str, is_lora: bool | None = None) -> float:
    """Return an AdamW LoRA SFT sweep starting point, not a tuned optimum.

    The value is ``reference_lr * get_lora_lr_multiplier(model_name)`` from
    ``lr_multipliers.json``. For adjustments, limitations and measurement details,
    see the [hyperparameter guide](https://github.com/thinking-machines-lab/tinker-cookbook/blob/main/skills/research/references/hyperparams.md).
    Use :func:`transfer_lr` to move a tuned LR between models.

    Args:
        model_name (str): Tinker model id; ``:peft:<context>`` suffixes are accepted.
        is_lora (bool | None): Deprecated. Tinker trains LoRA adapters; passing
            ``False`` raises.

    Returns:
        float: Learning rate.

    Raises:
        ConfigurationError: If the model has no calibrated LR.
    """
    if is_lora is not None:
        warnings.warn(
            "get_lr(is_lora=...) is deprecated; learning rates are calibrated for LoRA only",
            DeprecationWarning,
            stacklevel=2,
        )
        if not is_lora:
            raise ConfigurationError("Full fine-tuning learning rates are not calibrated")
    return float(_lr_table()["reference_lr"]) * get_lora_lr_multiplier(model_name)


